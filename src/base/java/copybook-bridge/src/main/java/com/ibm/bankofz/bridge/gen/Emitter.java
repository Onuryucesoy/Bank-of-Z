package com.ibm.bankofz.bridge.gen;

import com.ibm.bankofz.bridge.gen.Item.Condition;
import com.ibm.bankofz.bridge.gen.Item.Literal;
import com.ibm.bankofz.bridge.runtime.Db2Table;
import com.ibm.bankofz.bridge.runtime.FieldSpec;
import com.ibm.bankofz.bridge.runtime.Hex;

import java.math.BigDecimal;
import java.nio.charset.Charset;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/** Turns a laid-out record into a Java source file. */
final class Emitter {
    static final String HEADER = "// GENERATED by com.ibm.bankofz.bridge.gen.Generate from %s -- DO NOT EDIT.\n"
            + "// Regenerate with: gradle -p src/base/java :copybook-bridge:generateCopybooks\n";

    private final Item record;
    private final String source;
    private final String pkg;
    private final String className;
    private final Charset charset;
    private final String charsetConst;
    private final List<Item> items = new ArrayList<>();
    private final Map<Item, String> constants = new HashMap<>();
    private final Map<Item, int[][]> dims = new HashMap<>();
    private final Set<String> methodNames = new HashSet<>();
    private final StringBuilder out = new StringBuilder();
    private int fillerCount;

    Emitter(Item record, String source, String pkg, String className, Charset charset, String charsetConst) {
        this.record = record;
        this.source = source;
        this.pkg = pkg;
        this.className = className;
        this.charset = charset;
        this.charsetConst = charsetConst;
    }

    String emit() {
        collect(record, new int[0], new int[0], "");
        assignNames();
        Item odo = findOdo();

        out.append(String.format(HEADER, source));
        out.append("package ").append(pkg).append(";\n\n");
        out.append("import com.ibm.bankofz.bridge.runtime.CobolRecord;\n");
        out.append("import com.ibm.bankofz.bridge.runtime.Ebcdic;\n");
        out.append("import com.ibm.bankofz.bridge.runtime.FieldSpec;\n");
        out.append("import com.ibm.bankofz.bridge.runtime.Hex;\n");
        out.append("import com.ibm.bankofz.bridge.runtime.RecordLayout;\n");
        out.append("import com.ibm.bankofz.bridge.runtime.ZonedDecimal;\n\n");
        out.append("import java.math.BigDecimal;\n");
        out.append("import java.util.List;\n\n");
        out.append("/**\n * Byte-exact view of {@code ").append(record.name).append("} from {@code ").append(source)
                .append("}: ").append(record.size).append(" bytes").append(odo == null ? "" : " at maximum OCCURS")
                .append(".\n */\n");
        out.append("@SuppressWarnings(\"unused\")\n");
        out.append("public final class ").append(className).append(" extends CobolRecord {\n");
        out.append("    public static final int LENGTH = ").append(record.size).append(";\n\n");
        for (Item it : items) {
            int[][] d = dims.get(it);
            out.append("    public static final FieldSpec ").append(constants.get(it)).append(" = new FieldSpec(")
                    .append(it.level).append(", ").append(it.isFiller() ? "\"FILLER\"" : Names.javaString(it.name))
                    .append(", ").append(Names.javaString(pathOf(it))).append(", ").append(it.offset).append(", ")
                    .append(it.size).append(", FieldSpec.Kind.").append(it.kind).append(", ").append(it.digits)
                    .append(", ").append(it.scale).append(", ").append(it.signed).append(", ZonedDecimal.Sign.")
                    .append(it.sign).append(", ")
                    .append(it.expandedPicture == null ? "null" : Names.javaString(it.picture)).append(", ")
                    .append(intArray(d[0])).append(", ").append(intArray(d[1])).append(", ").append(it.underRedefines)
                    .append(", ").append(dependingOn(it) == null ? "null" : Names.javaString(dependingOn(it)))
                    .append(");\n");
        }
        out.append("\n    public static final RecordLayout LAYOUT = new RecordLayout(")
                .append(Names.javaString(record.name)).append(", ").append(Names.javaString(source))
                .append(", LENGTH, Ebcdic.").append(charsetConst).append(", List.of(");
        for (int i = 0; i < items.size(); i++) {
            out.append(i == 0 ? "\n            " : ",\n            ").append(constants.get(items.get(i)));
        }
        out.append("));\n");
        emitConditionConstants();
        if (odo != null) {
            out.append("\n    /** Offset of the OCCURS DEPENDING ON table {@code ").append(odo.name).append("}. */\n");
            out.append("    public static final int ODO_TABLE_OFFSET = ").append(odo.offset).append(";\n");
            out.append("    public static final int ODO_STRIDE = ").append(odo.size).append(";\n");
        }
        out.append("\n    public ").append(className).append("() {\n        this(new byte[LENGTH], 0);\n    }\n\n");
        out.append("    public ").append(className).append("(byte[] buffer) {\n        this(buffer, 0);\n    }\n\n");
        out.append("    public ").append(className).append("(byte[] buffer, int offset) {\n        super(LAYOUT, buffer, offset")
                .append(odo == null ? "" : ", ODO_TABLE_OFFSET").append(");\n    }\n");
        if (odo != null) {
            Item object = findByName(odo.dependingOn);
            out.append("\n    /** Length up to the last occurrence in use, per {@code ").append(odo.dependingOn).append("}. */\n");
            out.append("    @Override\n    public int actualLength() {\n        return ODO_TABLE_OFFSET + ODO_STRIDE * ")
                    .append("(int) getDecimal(").append(constants.get(object)).append(").longValueExact();\n    }\n");
        }
        emitApplyValues();
        for (Item it : items) {
            if (!it.isFiller()) {
                emitAccessors(it);
            }
            for (Condition c : it.conditions) {
                emitCondition(it, c);
            }
        }
        out.append("}\n");
        return out.toString();
    }

    static String emitTable(Db2Table t, String pkg, String className) {
        StringBuilder sb = new StringBuilder(String.format(HEADER, t.source()));
        sb.append("package ").append(pkg).append(";\n\n");
        sb.append("import com.ibm.bankofz.bridge.runtime.Db2Table;\n\nimport java.util.List;\n\n");
        sb.append("/** Db2 table {@code ").append(t.name()).append("} as declared in {@code ").append(t.source())
                .append("}. */\n");
        sb.append("public final class ").append(className).append(" {\n");
        sb.append("    public static final Db2Table TABLE = new Db2Table(").append(Names.javaString(t.name()))
                .append(", ").append(Names.javaString(t.source())).append(", List.of(");
        for (int i = 0; i < t.columns().size(); i++) {
            Db2Table.Column c = t.columns().get(i);
            sb.append(i == 0 ? "\n            " : ",\n            ").append("new Db2Table.Column(")
                    .append(Names.javaString(c.name())).append(", ").append(Names.javaString(c.type())).append(", ")
                    .append(c.length()).append(", ").append(c.scale()).append(", ").append(c.nullable()).append(")");
        }
        sb.append("));\n\n    private ").append(className).append("() {\n    }\n}\n");
        return sb.toString();
    }

    private void collect(Item it, int[] counts, int[] strides, String parentPath) {
        int[] c = counts;
        int[] s = strides;
        if (it.occursMax != 0) {
            c = Arrays.copyOf(counts, counts.length + 1);
            s = Arrays.copyOf(strides, strides.length + 1);
            c[counts.length] = it.occursMax;
            s[strides.length] = it.size;
        }
        dims.put(it, new int[][] {c, s});
        items.add(it);
        for (Item child : it.children) {
            collect(child, c, s, parentPath);
        }
    }

    private void assignNames() {
        Map<String, Integer> counts = new HashMap<>();
        for (Item it : items) {
            if (!it.isFiller()) {
                counts.merge(Names.pascal(it.name), 1, Integer::sum);
            }
        }
        Set<String> used = new HashSet<>();
        for (Item it : items) {
            String cobol;
            if (it.isFiller()) {
                cobol = "FILLER-" + (++fillerCount);
            } else {
                cobol = it.name;
                for (Item p = it.parent; counts.get(Names.pascal(it.name)) > 1 && p != null; p = p.parent) {
                    if (!p.isFiller()) {
                        cobol = cobol + "-OF-" + p.name;
                        break;
                    }
                }
            }
            String unique = cobol;
            for (int n = 2; !used.add(Names.pascal(unique)); n++) {
                unique = cobol + "-" + n;
            }
            it.javaName = Names.pascal(unique);
            constants.put(it, Names.constant(unique));
        }
    }

    private String pathOf(Item it) {
        List<String> parts = new ArrayList<>();
        for (Item i = it; i != null; i = i.parent) {
            parts.add(0, i.isFiller() ? i.javaName.toUpperCase() : i.name);
        }
        return String.join("/", parts);
    }

    private static String dependingOn(Item it) {
        for (Item i = it; i != null; i = i.parent) {
            if (i.dependingOn != null) {
                return i.dependingOn;
            }
        }
        return null;
    }

    private Item findOdo() {
        Item odo = null;
        for (Item it : items) {
            if (it.dependingOn != null) {
                if (odo != null) {
                    throw Layout.fail(source, it, "more than one OCCURS DEPENDING ON table");
                }
                if (dims.get(it)[0].length != 1) {
                    throw Layout.fail(source, it, "nested OCCURS DEPENDING ON is not supported");
                }
                if (it.offset + it.size * it.occursMax != record.size) {
                    throw Layout.fail(source, it, "items after an OCCURS DEPENDING ON table are not supported");
                }
                odo = it;
            }
        }
        if (odo != null && findByName(odo.dependingOn) == null) {
            throw Layout.fail(source, odo, "ODO object " + odo.dependingOn + " is not in this record");
        }
        return odo;
    }

    private Item findByName(String name) {
        for (Item it : items) {
            if (name.equals(it.name)) {
                return it;
            }
        }
        return null;
    }

    private void emitAccessors(Item it) {
        int n = dims.get(it)[0].length;
        String params = params(n, false);
        String paramsTrail = params(n, true);
        String args = args(n);
        String c = constants.get(it);
        String p = it.javaName;
        javadoc(it);
        switch (it.kind) {
            case GROUP -> {
                method("public byte[] get" + p + "Bytes(" + params + ") {\n        return getBytes(" + c + args + ");\n    }");
                method("public void set" + p + "Bytes(byte[] value" + paramsTrail + ") {\n        setBytes(" + c + ", value"
                        + args + ");\n    }");
            }
            case POINTER -> {
                method("public byte[] get" + p + "(" + params + ") {\n        return getBytes(" + c + args + ");\n    }");
                method("public void set" + p + "(byte[] value" + paramsTrail + ") {\n        setRaw(" + c + ", value"
                        + args + ");\n    }");
            }
            case ALPHANUMERIC -> {
                method("public String get" + p + "(" + params + ") {\n        return getString(" + c + args + ");\n    }");
                method("public void set" + p + "(String value" + paramsTrail + ") {\n        setString(" + c + ", value"
                        + args + ");\n    }");
            }
            default -> {
                if (it.scale == 0 && it.digits <= 18) {
                    method("public long get" + p + "(" + params + ") {\n        return getLong(" + c + args + ");\n    }");
                    method("public void set" + p + "(long value" + paramsTrail + ") {\n        setLong(" + c + ", value"
                            + args + ");\n    }");
                } else {
                    method("public BigDecimal get" + p + "(" + params + ") {\n        return getDecimal(" + c + args
                            + ");\n    }");
                    method("/** MOVE semantics: excess decimals and high-order digits are truncated. */\n"
                            + "    public void set" + p + "(BigDecimal value" + paramsTrail + ") {\n        setDecimal(" + c
                            + ", value, false" + args + ");\n    }");
                    method("/** COMPUTE ... ROUNDED semantics: half away from zero, then high-order truncation. */\n"
                            + "    public void set" + p + "Rounded(BigDecimal value" + paramsTrail + ") {\n        setDecimal("
                            + c + ", value, true" + args + ");\n    }");
                }
                if (it.kind == FieldSpec.Kind.ZONED || it.kind == FieldSpec.Kind.PACKED) {
                    method("/** COBOL class test {@code IF " + it.name + " NUMERIC}. */\n    public boolean is" + p
                            + "Numeric(" + params + ") {\n        return isNumericValid(" + c + args + ");\n    }");
                }
            }
        }
    }

    private void emitConditionConstants() {
        for (Item it : items) {
            for (Condition cond : it.conditions) {
                String name = condConst(it, cond);
                if (isTextual(it)) {
                    out.append("    private static final byte[][] ").append(name).append(" = {");
                    for (int i = 0; i < cond.ranges().size(); i++) {
                        Literal[] r = cond.ranges().get(i);
                        if (r[0] != r[1]) {
                            throw Layout.fail(source, it, "THRU on an alphanumeric 88 is not supported");
                        }
                        out.append(i == 0 ? "" : ", ").append("Hex.parse(\"").append(Hex.of(image(it, r[0])))
                                .append("\")");
                    }
                    out.append("};\n");
                } else {
                    out.append("    private static final BigDecimal[][] ").append(name).append(" = {");
                    for (int i = 0; i < cond.ranges().size(); i++) {
                        Literal[] r = cond.ranges().get(i);
                        out.append(i == 0 ? "" : ", ").append("{new BigDecimal(\"").append(number(it, r[0]))
                                .append("\"), new BigDecimal(\"").append(number(it, r[1])).append("\")}");
                    }
                    out.append("};\n");
                }
            }
        }
    }

    private void emitCondition(Item it, Condition cond) {
        int n = dims.get(it)[0].length;
        String params = params(n, false);
        String args = args(n);
        String c = constants.get(it);
        String pascal = Names.pascal(cond.name());
        String values = cond.ranges().stream()
                .map(r -> r[0] == r[1] ? show(r[0]) : show(r[0]) + " THRU " + show(r[1]))
                .reduce((a, b) -> a + " " + b).orElse("");
        String doc = "/** Level 88 {@code " + cond.name() + "} VALUE " + escapeDoc(values) + ". */\n    ";
        String is = uniqueMethod("is" + pascal);
        if (isTextual(it)) {
            method(doc + "public boolean " + is + "(" + params + ") {\n        return matchesAny(" + c + ", "
                    + condConst(it, cond) + args + ");\n    }");
            method("/** {@code SET " + cond.name() + " TO TRUE}. */\n    public void " + uniqueMethod("set" + pascal)
                    + "(" + params + ") {\n        setRaw(" + c + ", " + condConst(it, cond) + "[0]" + args + ");\n    }");
        } else {
            method(doc + "public boolean " + is + "(" + params + ") {\n        return inRanges(" + c + ", "
                    + condConst(it, cond) + args + ");\n    }");
            method("/** {@code SET " + cond.name() + " TO TRUE}. */\n    public void " + uniqueMethod("set" + pascal)
                    + "(" + params + ") {\n        setDecimal(" + c + ", " + condConst(it, cond) + "[0][0], false"
                    + args + ");\n    }");
        }
    }

    private void emitApplyValues() {
        List<String> lines = new ArrayList<>();
        for (Item it : items) {
            if (it.values.isEmpty()) {
                continue;
            }
            if (dims.get(it)[0].length != 0) {
                throw Layout.fail(source, it, "VALUE inside OCCURS is not supported");
            }
            String c = constants.get(it);
            if (isTextual(it)) {
                lines.add("setRaw(" + c + ", Hex.parse(\"" + Hex.of(image(it, it.values.get(0))) + "\"));");
            } else {
                lines.add("setDecimal(" + c + ", new BigDecimal(\"" + number(it, it.values.get(0)) + "\"), false);");
            }
        }
        if (lines.isEmpty()) {
            return;
        }
        out.append("\n    /** Applies the copybook's VALUE clauses (WORKING-STORAGE initial values). */\n");
        out.append("    public void applyValues() {\n");
        for (String l : lines) {
            out.append("        ").append(l).append('\n');
        }
        out.append("    }\n");
    }

    private boolean isTextual(Item it) {
        return it.kind == FieldSpec.Kind.ALPHANUMERIC || it.kind == FieldSpec.Kind.GROUP
                || it.kind == FieldSpec.Kind.EDITED;
    }

    private byte[] image(Item it, Literal lit) {
        byte[] img = new byte[it.size];
        byte space = " ".getBytes(charset)[0];
        Arrays.fill(img, space);
        byte[] src = switch (lit.type()) {
            case STRING, NUMBER -> lit.text().getBytes(charset);
            case HEX -> Hex.parse(lit.text());
            case SPACE -> new byte[0];
            case ZERO -> repeat("0".getBytes(charset)[0], it.size);
            case LOW_VALUE -> repeat((byte) 0, it.size);
            case HIGH_VALUE -> repeat((byte) 0xFF, it.size);
        };
        System.arraycopy(src, 0, img, 0, Math.min(src.length, img.length));
        return img;
    }

    private String number(Item it, Literal lit) {
        return switch (lit.type()) {
            case NUMBER -> new BigDecimal(lit.text()).toPlainString();
            case ZERO -> "0";
            default -> throw Layout.fail(source, it, "literal " + lit + " on a numeric item");
        };
    }

    private static byte[] repeat(byte b, int n) {
        byte[] a = new byte[n];
        Arrays.fill(a, b);
        return a;
    }

    private static String show(Literal l) {
        return switch (l.type()) {
            case STRING -> "'" + l.text() + "'";
            case HEX -> "X'" + l.text() + "'";
            case NUMBER -> l.text();
            default -> l.type().name().replace('_', '-');
        };
    }

    private static String escapeDoc(String s) {
        return s.replace("*/", "*&#47;").replace("@", "&#64;").replace("{", "&#123;").replace("}", "&#125;");
    }

    private String condConst(Item it, Condition c) {
        return "V_" + constants.get(it) + "_" + Names.constant(c.name());
    }

    private void javadoc(Item it) {
        StringBuilder code = new StringBuilder().append(it.level).append(' ').append(it.name);
        if (it.picture != null) {
            code.append(" PIC ").append(it.picture);
        }
        if (it.kind != FieldSpec.Kind.GROUP && !it.effectiveUsage().equals("DISPLAY")) {
            code.append(' ').append(it.effectiveUsage());
        }
        StringBuilder sb = new StringBuilder("    /** {@code ").append(escapeDoc(code.toString())).append("}, offset ")
                .append(it.offset).append(", ").append(it.size).append(" byte(s)");
        if (dims.get(it)[0].length > 0) {
            sb.append(", OCCURS ").append(Arrays.toString(dims.get(it)[0])).append(" (0-based subscripts)");
        }
        if (it.redefines != null) {
            sb.append(", REDEFINES ").append(it.redefines);
        }
        out.append('\n').append(sb).append(". */\n");
    }

    private String uniqueMethod(String name) {
        String n = name;
        for (int i = 2; methodNames.contains(n); i++) {
            n = name + i;
        }
        return n;
    }

    private void method(String body) {
        String sig = body.substring(body.indexOf("public "));
        String name = sig.substring(0, sig.indexOf('(')).replaceAll(".* ", "");
        if (!methodNames.add(name)) {
            throw new IllegalStateException(source + ": duplicate generated method " + name);
        }
        if (!out.toString().endsWith("*/\n")) {
            out.append('\n');
        }
        out.append("    ").append(body).append('\n');
    }

    private static String params(int n, boolean trailing) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < n; i++) {
            sb.append(i == 0 && !trailing ? "" : ", ").append("int i").append(i);
        }
        return sb.toString();
    }

    private static String args(int n) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < n; i++) {
            sb.append(", i").append(i);
        }
        return sb.toString();
    }

    private static String intArray(int[] a) {
        if (a.length == 0) {
            return "new int[0]";
        }
        StringBuilder sb = new StringBuilder("new int[] {");
        for (int i = 0; i < a.length; i++) {
            sb.append(i == 0 ? "" : ", ").append(a[i]);
        }
        return sb.append('}').toString();
    }
}
