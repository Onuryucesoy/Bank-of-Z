-- ACCOUNT and CUSTOMER as defined in .setup/jcl/cics/Db2-create.j2 (tablespace clauses removed)
CREATE SCHEMA BANKZ;

CREATE TABLE BANKZ.ACCOUNT (
    ACCOUNT_EYECATCHER             CHAR(4),
    ACCOUNT_CUSTOMER_NUMBER        CHAR(10),
    ACCOUNT_SORTCODE               CHAR(6) NOT NULL,
    ACCOUNT_NUMBER                 CHAR(8) NOT NULL,
    ACCOUNT_TYPE                   CHAR(8),
    ACCOUNT_INTEREST_RATE          DECIMAL(6, 2),
    ACCOUNT_OPENED                 DATE,
    ACCOUNT_OVERDRAFT_LIMIT        INTEGER,
    ACCOUNT_LAST_STATEMENT         DATE,
    ACCOUNT_NEXT_STATEMENT         DATE,
    ACCOUNT_AVAILABLE_BALANCE      DECIMAL(12, 2),
    ACCOUNT_ACTUAL_BALANCE         DECIMAL(12, 2)
);
CREATE UNIQUE INDEX BANKZ.ACCTINDX ON BANKZ.ACCOUNT(ACCOUNT_SORTCODE, ACCOUNT_NUMBER);
CREATE INDEX BANKZ.ACCTCUST ON BANKZ.ACCOUNT(ACCOUNT_SORTCODE, ACCOUNT_CUSTOMER_NUMBER);

CREATE TABLE BANKZ.CUSTOMER (
    CUSTOMER_EYECATCHER            CHAR(4),
    CUSTOMER_SORTCODE              CHAR(6) NOT NULL,
    CUSTOMER_NUMBER                CHAR(10) NOT NULL,
    CUSTOMER_TITLE                 CHAR(10),
    CUSTOMER_FIRST_NAME            CHAR(50),
    CUSTOMER_LAST_NAME             CHAR(50),
    CUSTOMER_DATE_OF_BIRTH         INTEGER,
    CUSTOMER_PHONE                 CHAR(20),
    CUSTOMER_ADDR_LINE1            CHAR(50),
    CUSTOMER_ADDR_LINE2            CHAR(50),
    CUSTOMER_CITY                  CHAR(50),
    CUSTOMER_POSTCODE              CHAR(10),
    CUSTOMER_COUNTRY               CHAR(50),
    CUSTOMER_STATUS                CHAR(10),
    CUSTOMER_CREATED_DATE          INTEGER,
    CUSTOMER_CREDIT_SCORE          SMALLINT,
    CUSTOMER_CS_REVIEW_DATE        INTEGER
);
CREATE UNIQUE INDEX BANKZ.CUSTINDX ON BANKZ.CUSTOMER(CUSTOMER_SORTCODE, CUSTOMER_NUMBER);
CREATE INDEX BANKZ.CUSTNAME ON BANKZ.CUSTOMER(CUSTOMER_LAST_NAME, CUSTOMER_FIRST_NAME);
