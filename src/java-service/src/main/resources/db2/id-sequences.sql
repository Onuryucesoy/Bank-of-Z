-- Post-cutover replacement for the BANKZCUST / BANKZACCT CONTROL rows.
-- NOT applied by any existing setup job. Run only when CRECUST/CREACC stop
-- allocating, with START WITH = (CONTROL_VALUE_NUM of the matching row) + 1:
--   SELECT CONTROL_VALUE_NUM FROM BANKZ.CONTROL WHERE CONTROL_NAME = 'BANKZCUST987654';
--   SELECT CONTROL_VALUE_NUM FROM BANKZ.CONTROL WHERE CONTROL_NAME = 'BANKZACCT987654';
CREATE SEQUENCE BANKZ.CUSTOMER_NUMBER_SEQ AS BIGINT
  START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999 NO CYCLE CACHE 20 ORDER;
CREATE SEQUENCE BANKZ.ACCOUNT_NUMBER_SEQ AS BIGINT
  START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 99999999 NO CYCLE CACHE 20 ORDER;
